#!/usr/bin/env python3
"""
Generate dnsmasq configuration from Netflix domain list.

Usage:
    python3 scripts/generate_dnsmasq_config.py <domain_file>

Output:
    configs/dnsmasq.netflix.conf
"""

import sys
import os
from datetime import datetime

def generate_config(domain_file, output_file):
    """Generate dnsmasq config from domain list."""

    if not os.path.exists(domain_file):
        print(f"[-] Domain file not found: {domain_file}")
        sys.exit(1)

    # Read domains
    with open(domain_file, 'r') as f:
        domains = [line.strip() for line in f if line.strip() and not line.startswith('#')]

    if not domains:
        print(f"[-] No domains found in {domain_file}")
        sys.exit(1)

    print(f"[*] Generating dnsmasq config for {len(domains)} domains...")

    # Generate address records
    address_lines = [f"address=/{domain}/127.0.0.1" for domain in domains]
    domains_section = "\n".join(address_lines)

    # Create config content
    config_content = f"""# Netflix Domain Interception Configuration
# Generated by setup.sh on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
#
# This file hijacks all Netflix domains to 127.0.0.1
# allowing the local MITM proxy to intercept traffic
#
# Total domains: {len(domains)}

# Enable DNS logging for debugging (uncomment if needed)
# log-queries

# Netflix domain address records
{domains_section}
"""

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_file), exist_ok=True)

    # Write config
    with open(output_file, 'w') as f:
        f.write(config_content)

    print(f"[+] Generated {output_file}")
    print(f"[+] Configuration includes {len(domains)} domain hijackings")

    return output_file

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: python3 scripts/generate_dnsmasq_config.py <domain_file>")
        sys.exit(1)

    domain_file = sys.argv[1]
    output_file = "configs/dnsmasq.netflix.conf"
    generate_config(domain_file, output_file)
